#!/usr/bin/env node
// Writes the three new-game input scripts of the opening harness (polite.input, annoyed.input, retry.input).
//
//   node tools/playtest/opening/build_inputs.js [--check]
//
// Each script is the same prefix (title -> name entry -> R1 wake -> R1 -> R1a -> R1b) followed by the R2..R3
// part of the matching file in tools/playtest/r2_floofy/, shifted to the tick Grub enters R1b. The R2 files were
// recorded from the R1b spawn at tick 0; shifted by that tick the dialog, intro and enemy turn starts line up exactly
// (same ticks relative to the room entry), only the battle's random numbers differ (the game seeds its RNG at the
// start of the run, and a longer prefix draws more of it), so the dodge moves of the R2 files are not the same
// dodges here. HP at the end of a fight therefore differs from the r2_floofy segments; the segments here only
// require that the fight is won.
//
// `--check` regenerates in memory and fails if a file on disk differs (use it after editing this script).

'use strict';

const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const R2_DIR = path.resolve(HERE, '..', 'r2_floofy');

// Ticks (30 per second) measured with --trace on the current build, see the header written into each file.
const FRONT_END = [
  '5 confirm',      // WARNING screen (Disclaimer)
  '40 cancel',      // Cancel skips the lore cards to the title (LoreScene)
  '150 confirm',    // PRESS START appears one second after the title opens -> Instructions (no save in the scratch folder)
  '200 confirm',    // Instructions: Begin game -> name entry
  '230 confirm',    // type "A"
  '236 up',         // wraps to the bottom row (Quit / Backspace / Done)
  '240 right',
  '244 right',      // Done
  '248 confirm',    // Done -> "Is this name correct?"
  '260 right',      // Yes
  '266 confirm',    // the white fade to R1 starts; the Overworld is pushed at tick 358
];
const WAKE_FIRST = 370;   // confirm every 10 ticks through r1_wake (it ends at tick 712)
const WAKE_LAST = 710;
const POKES_FIRST = 720;  // annoyed only: confirm facing Floofy (he is under the spawn) = one r1_floofy_poke each
const POKES_LAST = 1070;  // the third poke ends at tick 1072; no tap after it, so exactly three pokes
const WALK_UP_FROM = { clean: 715, poked: POKES_LAST + 10 };
const ROOM_WALK_TICKS = 136; // holding up from R1 (after the wake) to the R1b arrival: 715 -> 851

const VARIANTS = [
  {
    file: 'polite.input',
    source: 'polite.input',
    pokes: false,
    title: 'polite: no pokes, "Sorry." / "...Okay.", the petal fight (ruins.floofy.fight = 1), Furiell, R3',
  },
  {
    file: 'annoyed.input',
    source: 'annoyed.input',
    pokes: false,
    title: 'annoyed: no pokes, "You broke my fall." / "Those are NOT petals.", the Bass Shake fight (fight = 2), Furiell, R3',
  },
  {
    file: 'pokes.input',
    source: 'annoyed.input',
    sourceUntil: 1040, // the R2 walk and intro text; the choice taps below replace the rest
    pokes: true,
    chooseRude: true,
    title: 'pokes: three R1 pokes, then "You broke my fall." in R2 (annoyed 1 at the intro, 2 after the choice); stops at the first battle turn',
  },
  {
    file: 'retry.input',
    source: 'retry.input',
    pokes: false,
    title: 'retry: polite walk, the soul stands still in the fourth turn until game over, WELCOME HOME at the R1b save, back into R2',
  },
];

function shiftedLines(sourceFile, offset, until = Infinity) {
  const lines = [];
  for (const raw of fs.readFileSync(sourceFile, 'utf8').split(/\r?\n/)) {
    const text = raw.replace(/#.*/, '').trim();
    if (!text) continue;
    const [ticks, key] = text.split(/\s+/);
    const match = /^(\d+)(?:-(\d+))?$/.exec(ticks);
    if (!match || !key) throw new Error(`${sourceFile}: cannot parse "${raw}"`);
    if (Number(match[1]) > until) continue;
    const from = Number(match[1]) + offset;
    lines.push(match[2] === undefined ? `${from} ${key}` : `${from}-${Number(match[2]) + offset} ${key}`);
  }
  return lines;
}

function build(variant) {
  const walkFrom = variant.pokes ? WALK_UP_FROM.poked : WALK_UP_FROM.clean;
  const r1bArrival = walkFrom + ROOM_WALK_TICKS;
  const out = [
    `# Opening from a NEW GAME, ${variant.title}.`,
    '# GENERATED by tools/playtest/opening/build_inputs.js: edit that script, not this file.',
    '# Launch with no room/spawn/flag arguments, a scratch LOCALAPPDATA (no save, and the game saves at the R1b star):',
    '#   nundertale_modern.exe --input <this file> --seconds <n> --trace <file>        (opening_walkthrough.js does this)',
    '# 30 ticks = 1 s, seed 0 (lockstep with --trace). Dialog text types out and only Confirm on a finished page',
    '# advances it, so Confirm is tapped every 10 ticks. Timeline (ticks): 5 WARNING -> 21 lore cards -> 56 title ->',
    '# 166 instructions -> 216 name entry -> 358 R1 (Grub lying) + r1_wake -> 712 r1_wake ends',
    variant.pokes
      ? `# -> 721..1072 three r1_floofy_poke -> walk up from ${walkFrom}`
      : `# -> walk up from ${walkFrom}`,
    `# -> R1a -> R1b at about ${r1bArrival}; everything after ${r1bArrival} is ${variant.source} of tools/playtest/r2_floofy/`,
    `# shifted by ${r1bArrival} (see its header for the R2 timeline, add ${r1bArrival}).`,
    ...FRONT_END,
  ];
  for (let t = WAKE_FIRST; t <= WAKE_LAST; t += 10) out.push(`${t} confirm`);
  if (variant.pokes) for (let t = POKES_FIRST; t <= POKES_LAST; t += 10) out.push(`${t} confirm`);
  out.push(`${walkFrom}-${r1bArrival - 1} up`);
  out.push(...shiftedLines(path.join(R2_DIR, variant.source), r1bArrival, variant.sourceUntil));
  if (variant.chooseRude) {
    // The three pokes add a Floofy line before choice 1, so the page comes ~50 ticks later than in the source file.
    // Right is harmless on any other page and a no-op once on the second option: tap it before every Confirm.
    out.push('# choice 1 lands at a different tick than in the source file: Right then Confirm, every 10 ticks');
    for (let t = 1043; t <= 1263; t += 10) out.push(`${t + r1bArrival - 1} right`, `${t + r1bArrival} confirm`);
  }
  return out.join('\n') + '\n';
}

function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const variant of VARIANTS) {
    const target = path.join(HERE, variant.file);
    const text = build(variant);
    if (check) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
      if (current !== text) {
        console.error(`stale: ${variant.file}`);
        stale += 1;
      }
    } else {
      fs.writeFileSync(target, text);
      console.log(`wrote ${variant.file} (${text.split('\n').length - 1} lines)`);
    }
  }
  return stale === 0 ? 0 : 1;
}

process.exit(main());
